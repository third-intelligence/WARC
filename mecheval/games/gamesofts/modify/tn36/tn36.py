class GameManager:
    """















    """

    game: ARCBaseGame
    animation_queue: List[GameEntity]
    left_panel: PanelController
    right_panel: PanelController
    selector_buttons: List[SelectorButtonToggle]
    slot_positions: List[Tuple[int, int]]
    slot_rotations: List[int]
    slot_scales: List[int]
    slot_programs: List[List[int]]
    slot_reset_flags: List[bool]
    user_programs: List[List[int]]
    current_slot: int

    @property
    def is_animating(self) -> bool:
        """"""
        return bool(self.animation_queue)

    @property
    def current_level(self) -> Level:
        """"""
        return self.game.current_level

    @property
    def is_solved(self) -> bool:
        """"""
        return self.right_panel.is_solved

    def __init__(self, game: ARCBaseGame) -> None:
        self.game            = game
        self.animation_queue = []


        panel_sprites = sorted(
            self.current_level.get_sprites_by_tag(SpriteTag.game_panel),
            key=lambda s: s.x,
        )
        self.left_panel  = PanelController(self, panel_sprites[0])
        self.right_panel = PanelController(self, panel_sprites[1])


        self.selector_buttons = []
        for spr in sorted(
            self.current_level.get_sprites_by_tag(SpriteTag.selector_button),
            key=lambda s: s.x,
        ):
            self.selector_buttons.append(SelectorButtonToggle(self, spr))


        self.slot_positions  = self.current_level.get_data("Positions")
        self.slot_rotations  = self.current_level.get_data("Rotations")
        self.slot_scales     = self.current_level.get_data("Scales")
        self.slot_programs   = self.current_level.get_data("Programs")
        self.slot_reset_flags = self.current_level.get_data("Reset")
        self.current_slot    = 0


        if self.slot_programs:
            self.user_programs = [[0] * len(p) for p in self.slot_programs]
            self._select_slot(0)

    def handle_click(self, x: int, y: int) -> None:
        """




        """
        clicked_selector: Optional[SelectorButtonToggle] = None
        for btn in self.selector_buttons:
            if btn.handle_click(x, y):
                clicked_selector = btn
                break

        if clicked_selector:
            self._on_selector_clicked(clicked_selector)
        elif self.left_panel.handle_click(x, y):
            self._start_left_execution()
        elif self.right_panel.handle_click(x, y):
            self._start_right_execution()

    def _on_selector_clicked(self, btn: SelectorButtonToggle) -> None:
        """


        """
        self._save_current_user_program()

        for b in self.selector_buttons:
            b.toggle(False)
        btn.toggle(True)
        slot_index = self.selector_buttons.index(btn)
        self._select_slot(slot_index)
        self._start_left_execution()

    def _save_current_user_program(self) -> None:
        """"""
        if self.left_panel.tablet.fixed:
            return
        self.user_programs[self.current_slot] = self.left_panel.tablet.read_bitmasks()

    def _select_slot(self, index: int) -> None:
        """"""
        self.current_slot = index
        col, row = self.slot_positions[self.current_slot]
        self.left_panel.set_block_grid_position(col, row)
        rotation = self.slot_rotations[self.current_slot]
        self.left_panel.set_block_rotation(rotation)
        scale = self.slot_scales[self.current_slot]
        self.left_panel.set_block_scale(scale)

        program = self.slot_programs[self.current_slot]
        self.left_panel.tablet.load_program(program)

        if self.current_slot < len(self.slot_reset_flags):
            self.left_panel.tablet.set_resettable(self.slot_reset_flags[self.current_slot])
        else:
            self.left_panel.tablet.set_resettable(True)

        if not self.left_panel.tablet.fixed:
            self.left_panel.tablet.write_bitmasks(self.user_programs[self.current_slot])

    def save_user_program(self) -> None:
        """"""
        self._save_current_user_program()

    def _start_left_execution(self) -> None:
        """"""
        self.left_panel.start_execution()
        self.animation_queue.append(self.left_panel)

    def _start_right_execution(self) -> None:
        """"""
        self.right_panel.start_execution()
        self.animation_queue.append(self.right_panel)

    def run_both(self) -> None:
        """"""
        self._start_left_execution()
        self._start_right_execution()

    def step(self) -> None:
        """


        """
        if self.animation_queue:
            for i in range(len(self.animation_queue) - 1, -1, -1):
                entity = self.animation_queue[i]
                if not entity.tick_animation():
                    del self.animation_queue[i]

    def find_entity_at(self, entities: List[_T_GameEntity], x: int, y: int) -> Optional[_T_GameEntity]:
        """"""
        for entity in entities:
            if entity.contains_point(x, y):
                return entity
        return None


