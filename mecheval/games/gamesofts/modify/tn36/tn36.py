class PanelController(GameEntity):
    """















    """


    block_init_x: int
    block_init_y: int
    block_init_rotation: int
    block_init_scale: int
    block_init_color: int


    block: Block
    target: Optional[TargetIndicator]
    barriers: List[GhostTileOverlay]
    ghost_overlays: List[GhostTileOverlay]
    scale_barriers: List["BarrierCell"]
    walls: List[Wall]
    grid: GridDisplay
    tablet: Tablet
    run_btn: Optional["SelectorButton"]


    exec_step: int
    program: List[int]
    goal_reached_pending: bool


    command_table: Dict[int, Callable[[], Any]]

    @property
    def tablet_board(self) -> Tablet:
        """"""
        return self.tablet

    @property
    def is_solved(self) -> bool:
        """"""
        if not self.target:
            return False
        return (
            self.block.x == self.target.x
            and self.block.y == self.target.y
            and self.block.scale == self.target.scale
            and self.block.rotation == self.target.rotation
            and self.block.color == self.target.color
        )

    def __init__(self, manager: "GameManager", sprite: Sprite):
        super().__init__(manager, sprite)

        self.walls          = self._find_walls()
        self.block          = self._find_block()
        self.target         = self._find_target()
        self.barriers       = self._find_ghost_overlays()
        self.ghost_overlays = self.barriers
        self.scale_barriers = self._find_scale_barriers()
        self.run_btn        = self._find_run_button()
        self._save_block_state()
        self.grid           = self._find_grid()
        self.tablet         = self._find_tablet()
        self.program        = self.tablet.bitmasks
        self.exec_step      = len(self.program)
        self._build_command_table()
        self.goal_reached_pending = False



    def _find_block(self) -> Block:
        """"""
        for spr in self.current_level.get_sprites_by_tag(SpriteTag.block):
            spr.set_blocking(BlockingMode.BOUNDING_BOX)
            if self.contains_point(spr.x, spr.y):
                return Block(self.game_manager, spr)
        raise ValueError("Block not found in panel")

    def _find_target(self) -> Optional[TargetIndicator]:
        """"""
        for spr in self.current_level.get_sprites_by_tag(SpriteTag.target_indicator):
            if self.contains_point(spr.x, spr.y):
                return TargetIndicator(self.game_manager, spr)
        return None

    def _find_ghost_overlays(self) -> List[GhostTileOverlay]:
        """


        """
        result: List[GhostTileOverlay] = []
        ghost_tiles = self.current_level.get_sprites_by_tag(SpriteTag.ghost_tile)
        for gt in ghost_tiles:
            gt.set_blocking(BlockingMode.BOUNDING_BOX)
        for overlay_spr in self.current_level.get_sprites_by_tag(SpriteTag.ghost_tile_overlay):
            if not self.contains_point(overlay_spr.x, overlay_spr.y):
                continue
            overlay_spr.set_blocking(BlockingMode.BOUNDING_BOX)

            paired_ghost = None
            for gt in ghost_tiles:
                if gt.collides_with(overlay_spr):
                    paired_ghost = gt
                    break
            if paired_ghost:
                result.append(GhostTileOverlay(self.game_manager, paired_ghost, overlay_spr))
        return result

    def _find_walls(self) -> List[Wall]:
        """"""
        result: List[Wall] = []
        for spr in self.current_level.get_sprites_by_tag(SpriteTag.colored_square):
            if not self.contains_point(spr.x, spr.y):
                continue
            spr.set_blocking(BlockingMode.BOUNDING_BOX)
            result.append(Wall(self.game_manager, spr))
        return result

    def _find_scale_barriers(self) -> List[BarrierCell]:
        """


        """
        result: List[BarrierCell] = []
        for spr in self.current_level.get_sprites_by_tag(SpriteTag.barrier):
            if not self.contains_point(spr.x, spr.y):
                continue
            spr.set_blocking(BlockingMode.BOUNDING_BOX)
            result.append(BarrierCell(self.game_manager, spr))
        return result

    def _find_run_button(self) -> Optional["SelectorButton"]:
        """"""
        for spr in self.current_level.get_sprites_by_tag(SpriteTag.run_button):
            if self.contains_point(spr.x, spr.y):
                return SelectorButton(self.game_manager, spr)
        return None

    def _find_grid(self) -> GridDisplay:
        """"""
        for spr in self.current_level.get_sprites_by_tag(SpriteTag.grid_display):
            if self.contains_point(spr.x, spr.y):
                return GridDisplay(self.game_manager, spr)
        raise ValueError("GridDisplay not found in panel")

    def _find_tablet(self) -> Tablet:
        """"""
        for spr in self.current_level.get_sprites_by_tag(SpriteTag.tablet):
            if self.contains_point(spr.x, spr.y):
                return Tablet(self.game_manager, spr)
        raise ValueError("Tablet not found in panel")

    def _save_block_state(self) -> None:
        """"""
        self.block_init_x        = self.block.x
        self.block_init_y        = self.block.y
        self.block_init_rotation = self.block.rotation
        self.block_init_scale    = self.block.scale
        self.block_init_color    = self.block.color

    def _build_command_table(self) -> None:
        """



















        """
        self.command_table = {
            0:  lambda: self.block.reset_anim(),
            1:  lambda: self._move_block(-STEP_SIZE, 0),
            2:  lambda: self._move_block(STEP_SIZE, 0),
            3:  lambda: self._move_block(0, STEP_SIZE),
            5:  lambda: self.block.rotate(90),
            6:  lambda: self.block.rotate(-90),
            7:  lambda: self.block.rotate(180),
            8:  lambda: self._scale_block(1),
            9:  lambda: self._scale_block(-1),
            10: lambda: self._move_block(STEP_SIZE * 2, 0),
            11: lambda: self._move_block(STEP_SIZE * 2, 0),
            12: lambda: self._move_block(-STEP_SIZE * 2, 0),
            13: lambda: self._move_block(-STEP_SIZE * 2, 0),
            14: lambda: self.block.set_color(COLOR_CMD_BLUE),
            15: lambda: self.block.set_color(COLOR_CMD_RED),
            16: lambda: self.block.rotate(270),
            33: lambda: self._move_block(0, -STEP_SIZE),
            34: lambda: self._move_block(-STEP_SIZE, 0),
            63: lambda: self.block.set_color(COLOR_CMD_PURPLE),
        }



    def _update_barrier_visibility(self) -> None:
        """


        """
        for barrier in self.scale_barriers:
            barrier.set_visible(True)
            if barrier.collides_with(self.block):
                if barrier.scale == self.block.scale:
                    barrier.set_visible(False)
                    break

    def _move_block(self, dx: int, dy: int) -> None:
        """



        """
        if not self.block.is_alive:
            return
        self.block.move(dx, dy)

        for wall in self.walls:
            if wall.collides_with(self.block):
                self.block.move(-dx, -dy)
                break

        for barrier in self.barriers:
            if barrier.collides_with(self.block):
                self.block.kill()
                break
        self._update_barrier_visibility()

    def _scale_block(self, delta: int) -> None:
        """"""
        if not self.block.is_alive:
            return
        self.block.adjust_scale(delta)
        for wall in self.walls:
            if wall.collides_with(self.block):
                self.block.adjust_scale(-delta)
                break
        for barrier in self.barriers:
            if barrier.collides_with(self.block):
                self.block.kill()
                break
        self._update_barrier_visibility()

    def handle_click(self, x: int, y: int) -> bool:
        """



        """
        if not self.contains_point(x, y):
            return False
        if self.tablet.handle_click(x, y):
            return False
        if self.run_btn and self.run_btn.handle_click(x, y):
            self.run_btn.activate()
            self.game_manager.animation_queue.append(self.run_btn)
            return True
        return False

    def start_execution(self) -> None:
        """"""
        self.program   = list(self.tablet.bitmasks)
        self.exec_step = 0
        self._reset_block()

    def _reset_block(self) -> None:
        """"""
        self.block.set_position(self.block_init_x, self.block_init_y)
        self.block.set_rotation(self.block_init_rotation)
        self.block.set_scale(self.block_init_scale)
        self.block.set_color(self.block_init_color)
        self.block.revive()
        for barrier in self.scale_barriers:
            barrier.set_visible(True)
            if barrier.collides_with(self.block):
                if barrier.scale == self.block.scale:
                    barrier.set_visible(False)
                    break

    def set_block_grid_position(self, col: int, row: int) -> None:
        """"""
        cols = self.grid.width // STEP_SIZE
        rows = self.grid.height // STEP_SIZE
        x = self.grid.x + cols // 2 * STEP_SIZE + col * STEP_SIZE
        y = self.grid.y + rows // 2 * STEP_SIZE + row * STEP_SIZE
        self.block_init_x = x
        self.block_init_y = y
        self.block.set_position(x, y)

    def set_block_rotation(self, rotation: int) -> None:
        """"""
        self.block_init_rotation = rotation
        self.block.set_rotation(rotation)

    def set_block_scale(self, scale: int) -> None:
        """"""
        self.block_init_scale = scale
        self.block.set_scale(scale)

    def _toggle_barriers_every_third_step(self) -> None:
        """"""
        if self.exec_step % 3 != 2:
            return
        for barrier in self.barriers:
            barrier.set_visible(not barrier.is_visible)
            if barrier.is_visible and barrier.collides_with(self.block):
                self.block.kill()

    def tick_animation(self) -> bool:
        """













        """
        any_pending = False
        if self.block.tick_animation():
            any_pending = True
        if self.target and self.target.tick_animation():
            any_pending = True
        if any_pending:
            return True

        if self.goal_reached_pending:
            self.goal_reached_pending = False
            if self.tablet.fixed:
                return True
            return False


        if self.exec_step > 0:
            self.tablet.tile_rows[self.exec_step - 1].set_visible(False)


        if self.exec_step >= len(self.program):

            for barrier in self.scale_barriers:
                barrier.set_visible(True)
                if barrier.collides_with(self.block):
                    if barrier.scale == self.block.scale:
                        self._save_block_state()
                        barrier.set_visible(False)
                        break
            if not self.is_solved:

                for barrier in self.barriers:
                    barrier.set_visible(not barrier.is_visible)
                if self.tablet.resettable:
                    self._reset_block()
                return False
            else:

                if self.tablet.fixed and self.tablet.resettable:
                    self._reset_block()
                    return False

                self.goal_reached_pending = True
                self.block.highlight_goal()
                if self.target:
                    self.target.highlight_goal()




                game = self.game_manager.game
                if hasattr(game, "_set_event") and hasattr(game, "_to_display_bbox"):
                    flash_list = list(game._log_state.get_event("goal_flash", []) or [])
                    bdx, bdy, bdw, bdh = game._to_display_bbox(self.block.sprite)
                    flash_list.append({
                        "name": self.block.sprite.name,
                        "dx": bdx, "dy": bdy, "dw": bdw, "dh": bdh,
                        "kind": "block",
                    })
                    if self.target:
                        tdx, tdy, tdw, tdh = game._to_display_bbox(self.target.sprite)
                        flash_list.append({
                            "name": self.target.sprite.name,
                            "dx": tdx, "dy": tdy, "dw": tdw, "dh": tdh,
                            "kind": "target",
                        })
                    game._set_event("goal_flash", flash_list)
                return True


        current_row = self.tablet.tile_rows[self.exec_step]
        mask = self.program[self.exec_step]
        current_row.set_visible(True)
        cmd = self.command_table.get(mask)
        if cmd:
            cmd()

        if self.exec_step < len(self.program) - 1:
            self._toggle_barriers_every_third_step()
        self.exec_step += 1
        return True


