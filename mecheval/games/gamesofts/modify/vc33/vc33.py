class MoveStep:
    """



    """

    sprite: Sprite
    dest: tuple[int, int]

    def __init__(self, sprite: Sprite, dest: tuple[int, int]) -> None:
        self.sprite = sprite
        self.dest = dest

    def advance(self) -> bool:
        """"""
        pos = (self.sprite.x, self.sprite.y)
        dst = self.dest

        dx = dst[0] - pos[0]
        dy = dst[1] - pos[1]

        if dx == 0 and dy == 0:
            return True


        if abs(dx) >= abs(dy):
            next_pos = (pos[0] + np.sign(dx), pos[1])
        else:
            next_pos = (pos[0], pos[1] + np.sign(dy))

        self.sprite.set_position(next_pos[0], next_pos[1])

        return False


class MoveSequence:
    """



    """

    move_steps: list[MoveStep]
    step_idx: int

    def __init__(self, move_steps: list[MoveStep]) -> None:
        self.move_steps = move_steps
        self.step_idx = 0

    def next(self) -> bool:
        """"""
        current = self.move_steps[self.step_idx]

        if current.advance():
            self.step_idx += 1

            if self.step_idx == len(self.move_steps):
                return True

        return False


class ClickTimer(RenderableUserDisplay):
    """






    """

    def __init__(self, max_val: int):
        self.max_val = max_val
        self.value = max_val

    def set_value(self, v: int) -> None:
        """"""
        self.value = max(0, min(v, self.max_val))

    def tick(self) -> bool:
        """"""
        if self.value > 0:
            self.value -= 1
        return self.value > 0

    def reset(self) -> None:
        """"""
        self.value = self.max_val

    def render_interface(self, frame: np.ndarray) -> np.ndarray:
        """"""
        if self.max_val == 0:
            return frame

        ratio = self.value / self.max_val
        filled = round(64 * ratio)

        for col in range(64):
            if col < filled:
                frame[0, col] = 7
            else:
                frame[0, col] = 4

        return frame




