    def _adjacent_bodies(self, slot: Sprite) -> list[Sprite]:
        """"""
        bodies = self.current_level.get_sprites_by_tag("pipe_body")
        return [b for b in bodies
                if self._perp(b) + self._perp_size(b) == self._perp(slot)
                or self._perp(b) == self._perp(slot) + self._perp_size(slot)]

    def _upstream_pieces(self, slot: Sprite) -> list[Sprite]:
        """"""
        pieces = self.current_level.get_sprites_by_tag("piece")
        if self._is_forward():
            return [p for p in pieces if self._perp(p) == self._perp(slot) and self._far_edge(p) < self._far_edge(slot)]
        else:
            return [p for p in pieces if self._perp(p) == self._perp(slot) and self._far_edge(p) > self._far_edge(slot)]

    def _at_pipe_end(self, joint: Sprite, slot: Sprite) -> bool:
        """"""
        return (self._perp(joint) >= self._perp(slot)
                and self._perp(joint) < self._perp(slot) + self._perp_size(slot)
                and self._far_edge(joint) == self._near_edge(slot))

    def _joints_at(self, slot: Sprite) -> list[Sprite]:
        """"""
        return [j for j in self.current_level.get_sprites_by_tag("joint")
                if self._at_pipe_end(j, slot)]



    def _stop_pos(self, slot: Sprite) -> int:
        """



        """
        upstream = self._upstream_pieces(slot)
        if upstream:
            if self._joints_at(slot):

                if self.flow_dir[0] == -3:
                    return max(self._far_edge(p) - 6 for p in upstream)
                else:
                    return max(self._far_edge(p) - 4 for p in upstream)
            else:
                return max(self._far_edge(p) for p in upstream)


        adj = self._adjacent_bodies(slot)
        if self._is_forward():
            return max(self._near_edge(b) for b in adj)
        else:
            return min(self._near_edge(b) for b in adj)

    def _push_pipes(self, slot_a: Sprite, slot_b: Sprite) -> bool:
        """





        """
        can_push = (self._para_size(slot_a) > 0
                    and ((self._is_forward()     and self._para(slot_b)      > self._stop_pos(slot_b))
                      or (not self._is_forward() and self._near_edge(slot_b) < self._stop_pos(slot_b))))
        if not can_push:
            return False

        dx, dy = self.flow_dir


        for j in self._joints_at(slot_a):
            j.move(dx, dy)
        for j in self._joints_at(slot_b):
            j.move(-dx, -dy)


        if dx >= 0:
            slot_a.move(dx, 0)
            slot_b.move(-dx, 0)
        if dy >= 0:
            slot_a.move(0, dy)
            slot_b.move(0, -dy)


        empty_row = np.full((1, slot_b.pixels.shape[1]), 0)
        if dx != 0:
            slot_a.pixels = slot_a.pixels[: -abs(dx)]
            for _ in range(abs(dx)):
                slot_b.pixels = np.vstack([slot_b.pixels, empty_row])
        else:
            slot_a.pixels = slot_a.pixels[: -abs(dy)]
            for _ in range(abs(dy)):
                slot_b.pixels = np.vstack([slot_b.pixels, empty_row])

        self._refresh_visuals()
        return True

    def _activate_connector(self, conn: Sprite) -> bool:
        """

        """
        slot_a, slot_b = self.valve_map[conn]
        return self._push_pipes(slot_a, slot_b)

    def _make_swap_anim(self, bar: Sprite) -> MoveSequence:
        """








        """
        all_slots = self.current_level.get_sprites_by_tag("pipe_slot")

        adjacent_slots = [s for s in all_slots if self._near_edge(s) == self._far_edge(bar)]


        slot_left  = [s for s in adjacent_slots if self._perp(s) + self._perp_size(s) == self._perp(bar)][0]
        slot_right = [s for s in adjacent_slots if self._perp(s) == self._perp(bar) + self._perp_size(bar)][0]

        move_list = []


        for j in self._joints_at(slot_left):
            if self.flow_dir[0] != 0:
                dest_y = slot_right.y + (slot_right.height // 2) - (j.height // 2)
                dest_x = j.x
            else:
                dest_x = slot_right.x + (slot_right.width // 2) - (j.width // 2)
                dest_y = j.y
            move_list.append(MoveStep(j, (dest_x, dest_y)))


        for j in self._joints_at(slot_right):
            if self.flow_dir[0] != 0:
                dest_y = slot_left.y + (slot_left.height // 2) - (j.height // 2)
                dest_x = j.x
            else:
                dest_x = slot_left.x + (slot_left.width // 2) - (j.width // 2)
                dest_y = j.y
            move_list.append(MoveStep(j, (dest_x, dest_y)))


        if self.flow_dir[0] > 0:
            slide_out = MoveStep(bar, (bar.x - bar.width, bar.y))
        elif self.flow_dir[0] < 0:
            slide_out = MoveStep(bar, (bar.x + bar.width, bar.y))
        else:
            slide_out = MoveStep(bar, (bar.x, bar.y - bar.height))

        slide_in = MoveStep(bar, (bar.x, bar.y))

        return MoveSequence([slide_out] + move_list + [slide_in])



