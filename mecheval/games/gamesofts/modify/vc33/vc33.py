                if behind:

                    ahead = [s for s in slots if self._perp(s) == self._perp(conn) + self._perp_size(conn) * 2 and self._is_past(s, conn)]
                    if self._is_forward():
                        slot_a = min(behind, key=lambda w: self._para(w))
                        slot_b = min(ahead,  key=lambda w: self._para(w))
                    else:
                        slot_a = max(behind, key=lambda w: self._para(w))
                        slot_b = max(ahead,  key=lambda w: self._para(w))

                    self.valve_map[conn] = (slot_b, slot_a)

