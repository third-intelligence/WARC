    def _is_connected(self, bar: Sprite) -> bool:
        """



        """
        slots_ahead = [s for s in self.current_level.get_sprites_by_tag("pipe_slot")
                       if self._near_edge(s) == self._far_edge(bar)]
        left  = [s for s in slots_ahead if self._perp(s) + self._perp_size(s) == self._perp(bar)]
        right = [s for s in slots_ahead if self._perp(s) == self._perp(bar) + self._perp_size(bar)]
        return bool(left and right)

    def _update_bar_visual(self, bar: Sprite) -> None:
        """



        """
        if self._is_connected(bar):
            bar.color_remap(None, ORANGE)


            if bar.pixels.shape[1] == 3:
                arrow = sprites["preview_12h7w"].clone()
            else:
                arrow = sprites["preview_8h6w"].clone()
            arrow.set_rotation(bar.rotation)


