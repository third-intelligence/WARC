        clickables = self.current_level.get_sprites_by_tag("clickable")
        scale, offset_x, offset_y = self.camera._calculate_scale_and_offset()
        actions: list[ActionInput] = []

        for s in clickables:
            if not self._is_sprite_clickable_now(s):
                continue

            disp_x = s._x * scale + offset_x
            disp_y = s._y * scale + offset_y
            actions.append(ActionInput(id=GameAction.ACTION6, data={"x": disp_x, "y": disp_y}))

        return actions

