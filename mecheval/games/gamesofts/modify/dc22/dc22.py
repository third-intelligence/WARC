        if sprite is other or "ignore" in sprite.tags or "ignore" in other.tags:
            return False
        if not ignoreMode:
            if not (sprite.is_collidable and other.is_collidable):
                return False
        if sprite._blocking == BlockingMode.NOT_BLOCKED or other._blocking == BlockingMode.NOT_BLOCKED:
            return False
        self_pixels = sprite.render()
        other_pixels = other.render()
        self_height, self_width = self_pixels.shape
        other_height, other_width = other_pixels.shape
        if sprite._x >= other._x + other_width or sprite._x + self_width <= other._x or sprite._y >= other._y + other_height or (sprite._y + self_height <= other._y):
            return False
        x_min = max(sprite._x, other._x)
        x_max = min(sprite._x + self_width, other._x + other_width)
        y_min = max(sprite._y, other._y)
        y_max = min(sprite._y + self_height, other._y + other_height)
        self_x_start = x_min - sprite._x
        self_x_end = x_max - sprite._x
        self_y_start = y_min - sprite._y
        self_y_end = y_max - sprite._y
        other_x_start = x_min - other._x
        other_x_end = x_max - other._x
        other_y_start = y_min - other._y
        other_y_end = y_max - other._y
        self_region = self_pixels[self_y_start:self_y_end, self_x_start:self_x_end]
        other_region = other_pixels[other_y_start:other_y_end, other_x_start:other_x_end]
        self_mask = self_region >= 0
        other_mask = other_region >= 0
        return bool(np.any(self_mask & other_mask))

