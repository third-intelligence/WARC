    def get_sprite_status(self) -> list[dict]:
        """




        """
        result = []

        _AUX_TAGS = {"sys_click"}
        for spr in self.current_level.get_sprites():
            if not spr.is_visible:
                continue
            tags     = list(spr._tags) if spr._tags else []

            tags_main = [t for t in tags if t not in _AUX_TAGS]
            label    = next(
                (TAG_DISPLAY_NAMES[t] for t in tags_main if t in TAG_DISPLAY_NAMES),
                next((TAG_DISPLAY_NAMES[t] for t in tags if t in TAG_DISPLAY_NAMES), spr.name),
            )
            label_l2 = next(
                (TAG_DISPLAY_NAMES_L2[t] for t in tags_main if t in TAG_DISPLAY_NAMES_L2),
                next((TAG_DISPLAY_NAMES_L2[t] for t in tags if t in TAG_DISPLAY_NAMES_L2), spr.name),
            )
            result.append({
                "spr_id":   id(spr),
                "name":     spr.name,
                "label":    label,
                "label_l2": label_l2,
                "tags":     tags,
                "x":        spr.x,
                "y":        spr.y,
                "width":    spr.width,
                "height":   spr.height,
                "rotation": spr.rotation,
            })
        return result

