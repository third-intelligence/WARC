    def advance_sprite(self, moving_spr: Sprite) -> None:
        if moving_spr.rotation == 0:
            moving_spr.set_position(moving_spr.x, moving_spr.y - 1)
        elif moving_spr.rotation == 180:
            moving_spr.set_position(moving_spr.x, moving_spr.y + 1)
        elif moving_spr.rotation == 270:
            moving_spr.set_position(moving_spr.x - 1, moving_spr.y)
        elif moving_spr.rotation == 90:
            moving_spr.set_position(moving_spr.x + 1, moving_spr.y)

    def move_and_check_aligned(self, moving_spr2: Sprite) -> bool:
        if moving_spr2.rotation == 0:
            moving_spr2.set_position(moving_spr2.x, moving_spr2.y - 1)
        elif moving_spr2.rotation == 180:
            moving_spr2.set_position(moving_spr2.x, moving_spr2.y + 1)
        elif moving_spr2.rotation == 270:
            moving_spr2.set_position(moving_spr2.x - 1, moving_spr2.y)
        elif moving_spr2.rotation == 90:
            moving_spr2.set_position(moving_spr2.x + 1, moving_spr2.y)
