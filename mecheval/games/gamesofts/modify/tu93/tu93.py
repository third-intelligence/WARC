    def remove_if_coincident(self, spr_a2: Sprite, spr_b2: Sprite) -> None:
        if spr_a2.x == spr_b2.x and spr_a2.y == spr_b2.y:
            self.current_level.remove_sprite(spr_b2)

    def mark_activated(self, act_spr: Sprite) -> None:
        act_spr.pixels[0, 1] = COLOR_ACTIVATED

    def mark_deactivated(self, deact_spr: Sprite) -> None:
        deact_spr.pixels[0, 1] = 15

    def is_facing_target(self, facing_spr: Sprite, target_spr: Sprite, dist: int) -> bool:
        return facing_spr.rotation == 90 and facing_spr.x == target_spr.x - dist and (facing_spr.y == target_spr.y) or (facing_spr.rotation == 270 and facing_spr.x == target_spr.x + dist and (facing_spr.y == target_spr.y)) or (facing_spr.rotation == 180 and facing_spr.x == target_spr.x and (facing_spr.y == target_spr.y - dist)) or (facing_spr.rotation == 0 and facing_spr.x == target_spr.x and (facing_spr.y == target_spr.y + dist))

    def is_activated(self, sprite: Sprite) -> bool:
        return bool(sprite.pixels[0, 1] == COLOR_ACTIVATED)

    def get_colored_balls_at(self, player_spr: Sprite) -> list[Sprite]:
        orange_balls = self.current_level.get_sprites_by_tag("orange_ball")
        teal_balls = self.current_level.get_sprites_by_tag("teal_ball")
        magenta_balls = self.current_level.get_sprites_by_tag("magenta_ball")
        all_balls = orange_balls + teal_balls + magenta_balls
        return [sprite for sprite in all_balls if sprites_coincide(player_spr, sprite)]

    def get_player_at(self, center_spr: Sprite) -> list[Sprite]:
        player_sprites = self.current_level.get_sprites_by_tag("player")
        return [sprite for sprite in player_sprites if sprites_coincide(center_spr, sprite)]

    def expand_or_remove_ball(self, sprite: Sprite) -> bool:
        ball_color = sprite.pixels[0, 0]
        height = sprite.pixels.shape[0]
        if height == 3:
            sprite.move(-1, -1)
            sprite.pixels = sprites["template_small"].pixels
            sprite.color_remap(None, ball_color)
            return False
        elif height == 5:
            sprite.move(-1, -1)
            sprite.pixels = sprites["template_medium"].pixels
            sprite.color_remap(None, ball_color)
            return False
        self.current_level.remove_sprite(sprite)
        return True

    def process_player_step(self, sprite: Sprite) -> bool:
        grid_spr = self.current_level.get_sprites_by_tag("maze_grid")[0]
        i = sprite.y - grid_spr.y
        xjsopnydkp = sprite.x - grid_spr.x
        if is_grid_aligned(i, xjsopnydkp):
            hit_sprites = self.get_colored_balls_at(sprite)
            return all([self.expand_or_remove_ball(target_spr) for target_spr in hit_sprites])
        self.advance_sprite(sprite)
        return False

    def activate_orange_balls_near_player(self) -> None:
        player_sprites = self.current_level.get_sprites_by_tag("player")
        orange_balls = self.current_level.get_sprites_by_tag("orange_ball")
        for ball_spr in orange_balls:
            if any([self.is_facing_target(ball_spr, player_spr, STEP_SIZE_2) for player_spr in player_sprites]):
                self.mark_activated(ball_spr)
                self.advance_sprite(ball_spr)

    def process_orange_ball(self, sprite: Sprite) -> bool:
        if not self.is_activated(sprite):
            return True
        grid_spr = self.current_level.get_sprites_by_tag("maze_grid")[0]
        i = sprite.y - grid_spr.y
        xjsopnydkp = sprite.x - grid_spr.x
        if is_grid_aligned(i, xjsopnydkp):
            hit_sprites = self.get_player_at(sprite)
            return all([self.expand_or_remove_ball(target_spr) for target_spr in hit_sprites])
        self.advance_sprite(sprite)
        return False

    def advance_teal_balls(self) -> None:
        teal_balls = self.current_level.get_sprites_by_tag("teal_ball")
        for sprite in teal_balls:
            self.advance_sprite(sprite)

