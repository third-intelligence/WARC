    def reverse_teal_balls_at_walls(self) -> None:
        teal_balls = self.current_level.get_sprites_by_tag("teal_ball")
        for teal_spr in teal_balls:
            grid_spr = self.current_level.get_sprites_by_tag("maze_grid")[0]
            dx = teal_spr.x - grid_spr.x
            dy = teal_spr.y - grid_spr.y
            height, width = grid_spr.pixels.shape
            if teal_spr.rotation == 0:
                i = dy - STEP_SIZE
                xjsopnydkp = dx
                if not (i >= 0 and xjsopnydkp >= 0 and (i < height) and (xjsopnydkp < width)) or grid_spr.pixels[i, xjsopnydkp] != 2:
                    teal_spr.set_rotation(180)
            elif teal_spr.rotation == 180:
                i = dy + STEP_SIZE
                xjsopnydkp = dx
                if not (i >= 0 and xjsopnydkp >= 0 and (i < height) and (xjsopnydkp < width)) or grid_spr.pixels[i, xjsopnydkp] != 2:
                    teal_spr.set_rotation(0)
            elif teal_spr.rotation == 90:
                i = dy
                xjsopnydkp = dx + STEP_SIZE
                if not (i >= 0 and xjsopnydkp >= 0 and (i < height) and (xjsopnydkp < width)) or grid_spr.pixels[i, xjsopnydkp] != 2:
                    teal_spr.set_rotation(270)
            elif teal_spr.rotation == 270:
                i = dy
                xjsopnydkp = dx - STEP_SIZE
                if not (i >= 0 and xjsopnydkp >= 0 and (i < height) and (xjsopnydkp < width)) or grid_spr.pixels[i, xjsopnydkp] != 2:
                    teal_spr.set_rotation(90)

