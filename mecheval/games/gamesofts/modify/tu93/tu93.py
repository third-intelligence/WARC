        player_sprites = self.current_level.get_sprites_by_tag("player")
        magenta_balls = self.current_level.get_sprites_by_tag("magenta_ball")
        for sprite in magenta_balls:
            if not self.is_activated(sprite) and any([self.is_facing_target(sprite, player_spr, STEP_SIZE_4) for player_spr in player_sprites]):
                self.mark_activated(sprite)
